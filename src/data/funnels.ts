export type FunnelTag = 'Lead Capture' | 'Booking' | 'Checkout' | 'Website'

export type Funnel = {
  file: string
  label: string
  tag: FunnelTag
  desc: string
  /** Public subfolder the HTML + thumbnail live under. Default 'funnels'. */
  dir?: 'funnels' | 'samples'
  /** Full-page screenshot shown in the modal instead of an iframe - for real,
   *  live sites that can't be embedded (most block framing). When set, the
   *  modal scrolls the image instead of loading `file`. */
  image?: string
  /** Shown in the modal's fake address bar in place of the local file path. */
  siteUrl?: string
}

/**
 * Your funnel pages and website samples. Every entry is a PLACEHOLDER page
 * generated by scripts/make-placeholder-sites.mjs.
 *
 * To add your own: drop the page's HTML in public/funnels/ (single pages) or
 * public/samples/ (full websites), add an entry here, then run
 * `node scripts/make-thumbs.mjs` to render its thumbnails.
 */

